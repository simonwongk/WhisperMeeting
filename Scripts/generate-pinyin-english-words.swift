// Generates Sources/WhisperCore/PinyinEnglishWords.swift (F768): the toneless pinyin syllables that
// are also common English words, so `TransliteratedTermCorrection` never reads "you", "a" or "ping"
// beside a Han character as a vocabulary name written half in pinyin.
//
// Derived, not hand-written, from two lists this Mac already has:
//   - the pinyin syllables: every CJK Unified Ideograph (U+4E00–U+9FFF) read through Foundation's
//     `.mandarinToLatin` and `.stripDiacritics` transforms, lowercased — exactly what
//     `MandarinSound.reading` does, so the syllables are the ones the correction compares against;
//   - the common English words: the vocabulary of NaturalLanguage's English word embedding
//     (`NLEmbedding.wordEmbedding(for: .english)`, about 57,000 everyday words). It holds "you",
//     "ping", "long", "man" and "yang" but not surnames such as "wang", "zhang", "li" or "chen", which
//     is what lets the correction keep doing its job.
//
// WhisperCore may not import NaturalLanguage (the purity rule), so the result is committed as a
// constant. Run:  swift Scripts/generate-pinyin-english-words.swift > Sources/WhisperCore/PinyinEnglishWords.swift
// The output depends on this Mac's macOS data; regenerate it deliberately, and review the diff.

import Foundation
import NaturalLanguage

guard let english = NLEmbedding.wordEmbedding(for: .english) else {
    FileHandle.standardError.write(Data("No English word embedding on this Mac.\n".utf8))
    exit(1)
}

var syllables = Set<String>()
for value in 0x4E00...0x9FFF {
    guard let scalar = Unicode.Scalar(value) else { continue }
    let text = String(Character(scalar))
    guard let latin = text.applyingTransform(.mandarinToLatin, reverse: false),
          let plain = latin.applyingTransform(.stripDiacritics, reverse: false)?.lowercased(),
          plain != text, !plain.isEmpty, plain.allSatisfy({ $0.isASCII && $0.isLetter }) else { continue }
    syllables.insert(plain)
}

let shared = syllables.filter { english.contains($0) }.sorted()
let rows = stride(from: 0, to: shared.count, by: 12).map { start in
    "        " + shared[start..<min(start + 12, shared.count)].map { "\"\($0)\"" }.joined(separator: ", ") + ","
}

print("""
// Generated by Scripts/generate-pinyin-english-words.swift (F768). Do not edit by hand.
// \(syllables.count) toneless pinyin syllables; \(shared.count) of them are also in NaturalLanguage's English
// word-embedding vocabulary (\(english.vocabularySize) words) on the Mac that generated this file.

import Foundation

enum PinyinEnglishWords {
    /// Toneless pinyin syllables that are also common English words. A single one of these beside a
    /// Han character is read as English, never as a vocabulary name written half in pinyin.
    static let words: Set<String> = [
\(rows.joined(separator: "\n"))
    ]
}
""")
